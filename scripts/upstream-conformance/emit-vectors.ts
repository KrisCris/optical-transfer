// Cross-implementation conformance oracle: emit containers and frames from the
// ACTUAL upstream v0.5.3 source, for the Rust port to consume.
import { packFile, packFrame, fnv1a, unpackFile, verifyFile } from "./shared/protocol.ts";
import { packSnippet } from "./shared/snippet.ts";
import { LTEncoder, LTDecoder } from "./shared/fountain.ts";
import { writeFileSync, readFileSync } from "node:fs";

const hex = (b: Uint8Array) => Buffer.from(b).toString("hex");

const cases: any[] = [];

// 1. Tiny, uncompressed (under the 768-byte gzip threshold).
{
  const bytes = new TextEncoder().encode("hello optical — 光学 ✅");
  const packed = await packFile("note.txt", "text/plain", bytes);
  cases.push({ id: "tiny-none", name: "note.txt", type: "text/plain",
    originalHex: hex(bytes), containerHex: hex(packed.container),
    compression: packed.compression });
}

// 2. Highly compressible, so the browser's CompressionStream gzip is what the
//    Rust receiver has to inflate.
{
  const bytes = new TextEncoder().encode("the same sentence over and over. ".repeat(400));
  const packed = await packFile("repeat.txt", "text/plain", bytes);
  cases.push({ id: "gzip", name: "repeat.txt", type: "text/plain",
    originalHex: hex(bytes), containerHex: hex(packed.container),
    compression: packed.compression });
}

// 3. Incompressible, over the threshold: gzip attempted and rejected.
{
  let s = 12345;
  const bytes = new Uint8Array(4096);
  for (let i = 0; i < bytes.length; i++) {
    s = (Math.imul(s, 1103515245) + 12345) | 0;
    bytes[i] = (s >>> 16) & 0xff;
  }
  const packed = await packFile("noise.bin", "application/octet-stream", bytes);
  cases.push({ id: "incompressible", name: "noise.bin", type: "application/octet-stream",
    originalHex: hex(bytes), containerHex: hex(packed.container),
    compression: packed.compression });
}

// 4. A snippet, plus a full lossy frame stream off the upstream encoder.
{
  const text = "snippet across the optical channel — 光学传输\n".repeat(60);
  const packed = await packSnippet(text);
  const blockLen = 128;
  const sessionId = 0x3c9a;
  const enc = new LTEncoder(packed.container, blockLen, sessionId);
  const frames: string[] = [];
  for (let seq = 0; seq < enc.k * 4; seq++) {
    if (seq % 5 === 4) continue; // dropped by the "camera"
    frames.push(hex(packFrame({
      sessionId, seq, k: enc.k, blockLen,
      totalLen: packed.container.length, payloadFnv: fnv1a(packed.container), flags: 0,
    }, enc.encode(seq))));
  }
  cases.push({ id: "snippet-stream", name: "snippet.txt",
    type: "application/vnd.decimen.snippet", text,
    originalHex: hex(new TextEncoder().encode(text)),
    containerHex: hex(packed.container), compression: packed.compression,
    k: enc.k, blockLen, sessionId, frames });
}


// A flat, greppable record format: a golden vector file is read by humans
// reviewing a wire-format change, and a JSON blob of hex strings is not.
const lines: string[] = [
  "# Cross-implementation conformance vectors.",
  "# Generated by the pinned upstream oracle, Decimen Optical Transfer v0.5.3,",
  "# commit 5301fc2020716b5a97d4edf6e1793c3dedbf6e17, running its own",
  "# shared/protocol.ts, shared/snippet.ts and shared/fountain.ts under Node 24.",
  "# Every container below was produced by browser APIs (crypto.subtle SHA-256,",
  "# CompressionStream gzip) -- not by this repository -- so a Rust build that",
  "# reads them is proven to interoperate rather than merely self-consistent.",
  "",
];
for (const c of cases) {
  lines.push(`case ${c.id}`);
  lines.push(`name ${c.name}`);
  lines.push(`type ${c.type}`);
  lines.push(`compression ${c.compression}`);
  if (c.k !== undefined) {
    lines.push(`k ${c.k}`);
    lines.push(`blockLen ${c.blockLen}`);
    lines.push(`sessionId ${c.sessionId}`);
  }
  lines.push(`original ${c.originalHex}`);
  lines.push(`container ${c.containerHex}`);
  for (const f of c.frames ?? []) lines.push(`frame ${f}`);
  lines.push("end", "");
}
writeFileSync(process.argv[2], lines.join("\n"));
console.error(`wrote ${cases.length} cases`);

// 5. The reverse direction: can upstream read what Rust produced?
const reversePath = process.argv[3];
if (reversePath) {
  const reverse = JSON.parse(readFileSync(reversePath, "utf8"));
  for (const c of reverse) {
    const container = Uint8Array.from(Buffer.from(c.containerHex, "hex"));
    const file = await unpackFile(container);
    const ok = await verifyFile(file);
    const bytesHex = hex(file.bytes);
    console.log(JSON.stringify({
      id: c.id, ok, nameMatch: file.name === c.name, typeMatch: file.type === c.type,
      bytesMatch: bytesHex === c.originalHex, compression: file.compression,
    }));
  }
}
